        "계약·대금·바이어 응대에서 우리 같은 회사가 어디서 구멍 나는지 짚어주더라고요.\n"
        "저희 회사 진단해보니 생각 못 한 지점이 보였습니다.\n"
        f"👉 {share_url}\n"
